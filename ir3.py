import pandas as pd
import numpy as np
from pgmpy.models import DiscreteBayesianNetwork
from pgmpy.inference import VariableElimination

def bayesian_heart_diagnosis():
    np.random.seed(42)
    n = 600
    data = pd.DataFrame({
        'Age': np.random.choice([0, 1], size=n, p=[0.45, 0.55]),
        'Chol': np.random.choice([0, 1], size=n, p=[0.5, 0.5]),
        'FBS': np.random.choice([0, 1], size=n, p=[0.8, 0.2]),
        'ExAng': np.random.choice([0, 1], size=n, p=[0.65, 0.35]),
    })

    prob = (0.2 + 0.25*data['Age'] + 0.25*data['Chol'] + 0.15*data['ExAng'] + 0.1*data['FBS']).clip(0, 0.95)
    data['HeartDisease'] = (np.random.rand(n) < prob).astype(int)

    model = DiscreteBayesianNetwork([
        ('Age', 'HeartDisease'),
        ('Chol', 'HeartDisease'),
        ('FBS', 'HeartDisease'),
        ('ExAng', 'HeartDisease')
    ])

    model.fit(data)
    infer = VariableElimination(model)

    res = infer.query(variables=['HeartDisease'], evidence={'Age': 1, 'Chol': 1, 'ExAng': 1, 'FBS': 0})
    print(res)

if __name__ == "__main__":
    bayesian_heart_diagnosis()