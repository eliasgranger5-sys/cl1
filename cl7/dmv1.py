import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

sample_data = {
    'Order_ID': [101, 102, 103, 104, 105, 105, 106, 107],
    'Customer_Name': ['Alice Smith', 'Bob Jones', 'Charlie Brown', 'David Lee', 'Eva Green', 'Eva Green', 'Frank White', None],
    'Product_Category': ['Electronics', 'Furniture', 'electronics', 'Clothing', 'Furniture', 'Furniture', 'Clothing', 'Electronics'],
    'Quantity': [2, 1, 3, np.nan, 5, 5, 2, 4],
    'Unit_Price': [500.0, 1200.0, 300.0, 50.0, 450.0, 450.0, 80.0, 700.0],
    'Order_Date': ['2025-01-10', '2025-01-12', '2025-01-15', '2025-01-18', '2025-01-20', '2025-01-20', '2025-01-22', '2025-01-25']
}

df_init = pd.DataFrame(sample_data)
df_init.iloc[:3].to_csv('sales_data.csv', index=False)
df_init.iloc[3:6].to_excel('sales_data.xlsx', index=False)
df_init.iloc[6:].to_json('sales_data.json', orient='records')

df_csv = pd.read_csv('sales_data.csv')
df_excel = pd.read_excel('sales_data.xlsx')
df_json = pd.read_json('sales_data.json')

print(df_csv.info())
print(df_excel.info())
print(df_json.info())

df_unified = pd.concat([df_csv, df_excel, df_json], ignore_index=True)
print(df_unified.head())
print(df_unified.isnull().sum())

df_unified['Customer_Name'] = df_unified['Customer_Name'].fillna('Unknown Customer')
df_unified['Quantity'] = df_unified['Quantity'].fillna(df_unified['Quantity'].median())
df_unified = df_unified.drop_duplicates()
df_unified['Product_Category'] = df_unified['Product_Category'].str.strip().str.title()

df_unified[['First_Name', 'Last_Name']] = df_unified['Customer_Name'].str.split(' ', n=1, expand=True)
df_unified['Total_Sales'] = df_unified['Quantity'] * df_unified['Unit_Price']
df_unified['Order_Date'] = pd.to_datetime(df_unified['Order_Date'])

print(df_unified.describe())
print("Total Sales:", df_unified['Total_Sales'].sum())
print("Average Order Value:", df_unified['Total_Sales'].mean())

category_sales = df_unified.groupby('Product_Category')['Total_Sales'].sum()
print(category_sales)

plt.figure(figsize=(15, 4))

plt.subplot(1, 3, 1)
category_sales.plot(kind='bar', color='steelblue')
plt.title('Total Sales by Category')
plt.ylabel('Sales')

plt.subplot(1, 3, 2)
category_sales.plot(kind='pie', autopct='%1.1f%%')
plt.title('Sales Distribution')
plt.ylabel('')

plt.subplot(1, 3, 3)
sns.boxplot(x='Product_Category', y='Total_Sales', data=df_unified)
plt.title('Sales Boxplot by Category')