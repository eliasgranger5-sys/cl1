import re
from collections import defaultdict

class InvertedIndex:
    def __init__(self):
        self.index = defaultdict(set)
        self.docs = {}

    def tokenize(self, text):
        return set(re.findall(r'\b\w+\b', text.lower()))

    def add_doc(self, doc_id, text):
        self.docs[doc_id] = text
        for term in self.tokenize(text):
            self.index[term].add(doc_id)

    def search(self, query, mode="AND"):
        terms = list(self.tokenize(query))
        if not terms:
            return set()

        if mode == "AND":
            res = self.index.get(terms[0], set()).copy()
            for term in terms[1:]:
                res &= self.index.get(term, set())
            return res

        res = set()
        for term in terms:
            res |= self.index.get(term, set())
        return res

