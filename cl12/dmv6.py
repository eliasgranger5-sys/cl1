import pandas as pd
import matplotlib.pyplot as plt

df = pd.read_csv("Sample.csv", encoding='windows-1252')

region_sales = df.groupby('Region')['Sales'].sum().reset_index()

plt.figure(figsize=(8, 5))
plt.bar(region_sales['Region'], region_sales['Sales'], color='teal')
plt.title('Total Sales by Region')
plt.show()

plt.figure(figsize=(8, 5))
plt.pie(region_sales['Sales'], labels=region_sales['Region'], autopct='%1.1f%%')
plt.title('Sales Distribution by Region')
plt.show()

top_regions = region_sales.sort_values(by='Sales', ascending=False).head(3)
print(top_regions)

category_region_sales = df.groupby(['Region', 'Category'])['Sales'].sum().unstack()

category_region_sales.plot(kind='bar', stacked=True, figsize=(10, 6))
plt.title('Sales by Region and Category (Stacked)')
plt.show()

category_region_sales.plot(kind='bar', figsize=(10, 6))
plt.title('Sales by Region and Category (Grouped)')
plt.show()