import requests
from bs4 import BeautifulSoup
from urllib.parse import urljoin
import pandas as pd

def crawler(base_url, pages=2):
    headers = {"User-Agent": "Mozilla/5.0"}
    data = []
    curr_url = base_url

    for _ in range(pages):
        if not curr_url:
            break

        resp = requests.get(curr_url, headers=headers)
        soup = BeautifulSoup(resp.text, "html.parser")

        for card in soup.select("article.product_pod"):
            title_tag = card.select_one("h3 > a")
            title = title_tag.get("title", "") if title_tag else ""
            link = urljoin(curr_url, title_tag.get("href", "")) if title_tag else ""

            price_tag = card.select_one("p.price_color")
            price = price_tag.text.strip() if price_tag else ""

            data.append({"Title": title, "Price": price, "URL": link})

        next_btn = soup.select_one("li.next > a")
        curr_url = urljoin(curr_url, next_btn.get("href")) if next_btn else None

    return pd.DataFrame(data)

if __name__ == "__main__":
    df = crawler("https://books.toscrape.com/catalogue/page-1.html")
