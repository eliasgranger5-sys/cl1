import pandas as pd
import numpy as np

real_estate_data = {
    'Property ID ': [1, 2, 3, 4, 5, 6, 7, 8],
    'Neighborhood': ['Downtown', 'Suburb', 'Downtown', 'Rural', 'Suburb', 'Downtown', 'Suburb', 'Rural'],
    'Property-Type': ['Residential', 'Residential', 'Commercial', 'Residential', 'Residential', 'Residential', 'Commercial', 'Residential'],
    'Square Footage': [1500, 2200, np.nan, 1800, 2500, 1200, 3000, 1600],
    'Year Built': [2005, 2010, 1995, 2020, np.nan, 2018, 2015, 1980],
    'Sale Price ($)': [350000, 420000, 800000, 310000, 460000, 3000000, 950000, 290000] # 3,000,000 is an intentional outlier
}
df_re = pd.DataFrame(real_estate_data)
df_re.to_csv('RealEstate_Prices.csv', index=False)

# 2. Create Mock Demographics Dataset (For Merging)
demo_data = {
    'Neighborhood': ['Downtown', 'Suburb', 'Rural'],
    'Avg_Income': [85000, 95000, 65000],
    'Schools_Rating': [8, 9, 6]
}
df_demo = pd.DataFrame(demo_data)
df_demo.to_csv('Neighborhood_Demographics.csv', index=False)

print("Datasets created successfully!")

# ==========================================
# Task 1: Import & Clean Column Names
# ==========================================
print("\n--- Task 1: Clean Column Names ---")
df = pd.read_csv('RealEstate_Prices.csv')

df.columns = (
    df.columns.str.strip()
    .str.lower()
    .str.replace(r'[ -\/]', '_', regex=True)
    .str.replace(r'[^\w\s]', '', regex=True)
)
print("Cleaned Columns:", df.columns.tolist())

# ==========================================
# Task 2: Handle Missing Values
# ==========================================
print("\n--- Task 2: Handle Missing Values ---")
df['square_footage'] = df['square_footage'].fillna(df['square_footage'].median())

most_frequent_year = df['year_built'].mode()[0]
df['year_built'] = df['year_built'].fillna(most_frequent_year)

print(df.isnull().sum())

# ==========================================
# Task 3: Perform Data Merging
# ==========================================
print("\n--- Task 3: Merge Datasets ---")
df_demo = pd.read_csv('Neighborhood_Demographics.csv')
df_demo.columns = df_demo.columns.str.strip().str.lower()

df_merged = pd.merge(df, df_demo, on='neighborhood', how='left')
print(f"Dataset shape after merge: {df_merged.shape}")

# ==========================================
# Task 4: Filter and Subset Data
# ==========================================
print("\n--- Task 4: Filter Data ---")
df_filtered = df_merged[
    (df_merged['property_type'] == 'Residential') &
    (df_merged['year_built'] >= 2000)
]
print(f"Records after filtering: {df_filtered.shape[0]}")

# ==========================================
# Task 5: Encode Categorical Variables
# ==========================================
print("\n--- Task 5: Encode Categoricals ---")
df_encoded = pd.get_dummies(df_filtered, columns=['neighborhood', 'property_type'], drop_first=True)
print("Columns after encoding:\n", df_encoded.columns.tolist())

# ==========================================
# Task 6: Aggregate the Data (CORRECTED)
# ==========================================
print("\n--- Task 6: Data Aggregation ---")

sale_col = [col for col in df_merged.columns if 'sale' in col][0]
id_col = [col for col in df_merged.columns if 'id' in col][0]

summary_stats = df_merged.groupby('neighborhood').agg(
    avg_sale_price=(sale_col, 'mean'),
    avg_sq_ft=('square_footage', 'mean'),
    property_count=(id_col, 'count')
).reset_index()

print("Summary Statistics:\n", summary_stats)

# ==========================================
# Task 7: Identify and Handle Outliers (CORRECTED)
# ==========================================
print("\n--- Task 7: Handle Outliers ---")

sale_col_encoded = [col for col in df_encoded.columns if 'sale' in col][0]

Q1 = df_encoded[sale_col_encoded].quantile(0.25)
Q3 = df_encoded[sale_col_encoded].quantile(0.75)
IQR = Q3 - Q1

lower_bound = Q1 - 1.5 * IQR
upper_bound = Q3 + 1.5 * IQR

df_final = df_encoded[
    (df_encoded[sale_col_encoded] >= lower_bound) &
    (df_encoded[sale_col_encoded] <= upper_bound)
]

print(f"Original encoded shape: {df_encoded.shape}")
print(f"Shape after removing outliers: {df_final.shape}")