import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
from statsmodels.tsa.seasonal import seasonal_decompose
from statsmodels.tsa.arima.model import ARIMA

df = pd.read_csv("AAPL.csv")
df['Date'] = pd.to_datetime(df['Date'])
df.set_index('Date', inplace=True)
df.sort_index(inplace=True)

plt.figure(figsize=(12, 5))
plt.plot(df.index, df['Close'])
plt.title('Historical Stock Price (Close)')
plt.show()

df['MA_30'] = df['Close'].rolling(window=30).mean()
df['MA_90'] = df['Close'].rolling(window=90).mean()

plt.figure(figsize=(12, 5))
plt.plot(df.index, df['Close'], label='Close')
plt.plot(df.index, df['MA_30'], label='30-Day MA', color='orange')
plt.plot(df.index, df['MA_90'], label='90-Day MA', color='red')
plt.title('Stock Price with Moving Averages')
plt.legend()
plt.show()

decomposition = seasonal_decompose(df['Close'].dropna(), model='multiplicative', period=30)
decomposition.plot()
plt.show()

plt.figure(figsize=(6, 4))
sns.heatmap(df[['Close', 'Volume']].corr(), annot=True, cmap='coolwarm')
plt.title('Correlation: Close vs Volume')
plt.show()

close_values = df['Close'].dropna().values
model = ARIMA(close_values, order=(5, 1, 0))
model_fit = model.fit()

forecast = model_fit.forecast(steps=30)

last_date = df.index[-1]
future_dates = pd.date_range(start=last_date, periods=31, freq='B')[1:]

plt.figure(figsize=(12, 5))
plt.plot(df.index, df['Close'], label='Historical')
plt.plot(future_dates, forecast, color='red', label='Forecast (Next 30 Days)')
plt.title('ARIMA Stock Price Forecast')
plt.legend()
plt.show()